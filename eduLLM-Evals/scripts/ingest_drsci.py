"""Convert the Dr. SCI open-ended 10K handoff into Scenario + Rubric Schema JSONL.

Source: https://huggingface.co/datasets/MiniByte-666/Dr.SCI -- an UNOFFICIAL reproduction of
the Dr. SCI dataset from "Improving Data and Reward Design for Scientific Reasoning in Large
Language Models" (Chen et al., 2026, arXiv 2602.08321).

WHAT DR. SCI IS, AND WHAT IT IS NOT. It is RL post-training data, not an evaluation benchmark:
one `train` split, ~890K rows, in verl reward format. The authors train on it and then measure
on GPQA / SuperGPQA / HLE / MMLU-Pro. Its rubrics exist to be a reinforcement-learning REWARD,
not a score -- which matters, because a reward tolerates noise that RL averages away over
millions of samples, while an eval score does not. The rubrics were generated by OpenAI o3 and
never human-verified. Treat the bank accordingly.

TWO HALVES, ONLY ONE OF WHICH THIS SCRIPT HANDLES:

    open-ended  (475,759 rows)  ~9.8 o3-generated rubric items each   <- THIS SCRIPT
    verifiable  (414,746 rows)  `rubric` is null; one answer match     (see notes below)

The verifiable half ships NO criteria, so it cannot carry a criterion-level q-matrix at all;
its only options are a single dimension or subject-as-skill. It is out of scope here.

INPUT is the pre-sampled 10K handoff (two JSONL files), not the raw parquet: 10,003 scenarios
stratified to exactly 1,429 questions per subject across the 7 open-ended subjects. There is no
open-ended mathematics in Dr. SCI -- the authors deleted it as predominantly proof-based.

THE 5-SKILL Q-MATRIX AXIS
-------------------------
Dr. SCI ships no skill labels, so the axis is ours. It was derived from 33,269 real rubric
items and is documented, with worked examples and its failure modes, in
data/dr-sci/SKILLS_AND_CRITERIA.md.

    factual_recall         the answer must CONTAIN a correct discrete claim -- fact, term,
                           value, definition, classification. No explanation demanded.
    mechanistic_reasoning  the answer must SHOW WHY -- causal chain, derivation, application
                           of a principle, comparison, justification.
    quantitative           formula selection, substitution, computation, units, conversions,
                           precision, sign conventions.
    presentation           clear, ordered, appropriately concise, followable.
    restraint              claims sized to evidence -- hedging, assumptions, scope, no
                           overgeneralisation. Catches many Pitfall criteria. Named
                           "restraint" and not "calibration" deliberately: this repo already
                           uses calibration for fitting the IRT model, and for the pipeline
                           split label below.

Why not the 8 subjects as skills (the obvious alternative): open-ended math is empty, physics
is 63% of the pool, `science` is 1.2%, and eight dimensions require 28 free latent correlations
where this repo's own earlier run already warned that THREE were not identifiable at n=82
persons (staging/mirt_run1_console.txt). Subject is kept as a scenario field to stratify and
slice on, which delivers the same insight without spending dimensions on it.

Assignment is by pattern rules over the criterion text. AGGREGATE SHARES ARE RELIABLE;
INDIVIDUAL ROW LABELS ARE NOT -- the recall/reasoning border in particular is fuzzy for roughly
a third of items, and reasoning deliberately takes precedence there on the grounds that
explaining why subsumes stating what. This is the weakest link in the pipeline; see the
`Hard cases` section of the skills doc before trusting any single theta.

CRITICALITY comes from Dr. SCI's own four-level importance tag, which prefixes every
`description` and parses on 99.97% of rows:

    Essential -> critical    (weight 4-5)   omission invalidates the answer
    Important -> standard    (weight 3-4)   absence severely weakens it
    Optional  -> optional    (weight 1-3)   secondary detail
    Pitfall   -> critical    (weight -1/-2) a mistake that must be penalised

PITFALL POLARITY. Pitfall criteria are INVERTED: they describe something the response must NOT
do, and Dr. SCI gives them negative weight. This pipeline is binary pass/fail with no polarity
concept, so a Pitfall is scored as "did the response AVOID this mistake" -- avoided = pass. The
criterion text is left verbatim (the judge must read it as a thing to avoid) and the original
sign is preserved in `source_weight` so nothing is lost. 17% of the bank is Pitfall items, so
this convention matters; it is stated in the rubric's `q_rationale` too.

No `difficulty` / `discrimination` / `irt_params` are written. Those are calibrated from real
judge responses; shipping synthetic stand-ins that read like measurements is worse than
shipping none. Dr. SCI's OWN difficulty (a success rate over 8 Qwen3-32B rollouts) is carried
onto the scenario as `source_difficulty` when the index is available -- note it is INVERTED
relative to its name: higher means EASIER, and 1.0 is absent because 8/8-solved questions were
deleted as trivial.

Run:
    python scripts/ingest_drsci.py                      # uses ~/Downloads handoff
    python scripts/ingest_drsci.py --scenarios A --rubrics B --out-dir data/dr-sci
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SCENARIOS = Path.home() / "Downloads" / "scenario_openended_10k.jsonl"
DEFAULT_RUBRICS = Path.home() / "Downloads" / "rubrics_openended_10k.jsonl"
DEFAULT_OUT = ROOT / "data" / "dr-sci"
DIFFICULTY_INDEX = ROOT / "cache" / "drsci" / "difficulty_index.json"

SOURCE_URL = "https://huggingface.co/datasets/MiniByte-666/Dr.SCI"
SPLIT = "calibration"
VERSION = "1.0"
USE_CASE = "scientific_reasoning"   # the handoff sets use_case = subject, which is a content
                                    # label; one real use case describes every row here

# Fixed q-matrix column order. Must not be reordered in place -- downstream MIRT code indexes
# skills positionally.
SKILLS = ["factual_recall", "mechanistic_reasoning", "quantitative", "presentation", "restraint"]

CRITICALITY_OF = {
    "Essential": "critical",
    "Important": "standard",
    "Optional": "optional",
    "Pitfall": "critical",     # a pitfall IS a critical failure when triggered
}

CATEGORY_RE = re.compile(r"^\s*(Essential|Important|Optional|Pitfall)\s+Criteria\s*:\s*", re.I)

# --- skill patterns --------------------------------------------------------------------
# Ordered by specificity. A criterion may match several (q_mapping is multi-hot); only the
# recall/reasoning pair is mutually exclusive, resolved in favour of reasoning.
P_RESTRAINT = re.compile(
    r"overgeneral|oversimplif|overstat|overclaim|hedge|caveat|limitation|assumption|uncertain"
    r"|does not imply|not imply|in all (respects|cases)|for all (stages|cases)|\bscope\b|nuance"
    r"|caution|misleading|unsupported|without (evidence|justification)|absolut|too strong"
    r"|acknowledg\w* (the )?(limit|uncertain|assum)|conflat|mixed evidence|refrain"
    r"|rather than (a )?(universal|general)", re.I)
P_PRESENTATION = re.compile(
    r"concis|clarity|clear(ly)? (and|,|present|structur|organi)|brev|succinct|readab|organi[sz]"
    r"|structur|logical flow|easy to (follow|comprehend|understand)|verbos|well.?organ|coherent"
    r"|format|presentation|without excessive|avoid(s|ing)? (unnecessary|excessive|redundan)"
    r"|precise (and clear )?termino|well.?labeled", re.I)
P_QUANTITATIVE = re.compile(
    r"calculat|comput|numeric|arithmetic|\bunits?\b|sig(nificant)?.?fig|formula|substitut"
    r"|equation|\bsolve|round|magnitude|digit|multipl(y|ies)|divid|plug"
    r"|dimension(al|ally)? (analysis|consistenc)|precision|decimal|conver(t|sion)"
    r"|intermediate algebra|integral|\d+\s*(cm|kg|m/s|mol|eV|K\b|J\b|N\b|%)|=\s*-?\d", re.I)
P_REASONING = re.compile(
    r"\b(explain\w*|deriv\w*|demonstrat\w*|justif\w*|reason\w*|because|why|mechanis\w*"
    r"|connect\w*|link\w*|leads? to|results? in|due to|causes?|applies|apply\w*|integrat\w*"
    r"|verif\w*|account\w* for|show(s|ing)? (how|that|why)|relat\w+ to|how (it|the|this)"
    r"|interpret\w*|analy[sz]\w*|compar\w*|contrast\w*|distinguish\w*|differenti\w*)\b", re.I)
# Demands only that the answer CONTAIN something. Very broad by design -- it is the default
# demand of a Dr. SCI criterion -- so P_REASONING overrides it (see assign_skills).
P_RECALL = re.compile(
    r"\b(states?|identif\w+|mention\w*|name[sd]?|lists?|defines?|recogni[sz]\w+|notes?"
    r"|specif\w+|cites?|report\w*|indicat\w*|makes? clear|acknowledg\w*|includ\w*|discuss\w*"
    r"|referenc\w*|address\w*|covers?|presents?|concludes?|articulat\w*|outlin\w*|describ\w*)\b",
    re.I)

Q_RATIONALE = {
    "factual_recall": "Satisfied by the response containing a correct discrete claim; no explanation is demanded.",
    "mechanistic_reasoning": "Demands a causal chain, derivation, application or comparison rather than a bare assertion.",
    "quantitative": "Turns on formula choice, computation, units or numerical precision.",
    "presentation": "Concerns the clarity, order or concision of the delivery rather than its content.",
    "restraint": "Concerns sizing claims to the evidence -- hedging, assumptions, scope, avoiding overreach.",
}

SCENARIO_KEYS = [
    "scenario_id", "use_case", "subject", "grade_band", "modality", "prompt",
    "conversation_context", "reference_solution", "criterion_ids", "source_difficulty",
    "source_dataset", "source", "split", "version",
]
RUBRIC_KEYS = [
    "criterion_id", "scenario_id", "criterion", "expected_evidence", "scoring_type",
    "score_anchors", "rubric_title", "category", "polarity", "source_weight",
    "primary_skill", "q_mapping", "q_rationale", "criticality", "objectivity",
    "explicitness", "source", "status", "version",
]


def flatten_prompt(prompt) -> str:
    """The handoff stores prompt as [{role, content}]; the schema wants a string.

    Dr. SCI wraps every question in a one-turn instruction template, so there is exactly one
    user message and no dialogue to preserve.
    """
    if isinstance(prompt, str):
        return prompt.strip()
    if isinstance(prompt, list):
        return "\n\n".join((t.get("content") or "").strip() for t in prompt if t.get("content")).strip()
    return ""


def split_category(description: str) -> tuple[str | None, str]:
    """Peel Dr. SCI's importance tag off the front of a criterion description."""
    m = CATEGORY_RE.match(description or "")
    if not m:
        return None, (description or "").strip()
    return m.group(1).title(), CATEGORY_RE.sub("", description).strip()


def assign_skills(text: str) -> list[str]:
    """Multi-hot skill assignment over SKILLS, in fixed order.

    Reasoning takes precedence over recall where both match: a criterion that demands an
    explanation is not satisfied by the bare fact, so scoring it as recall would understate
    what it tests. Anything matching nothing falls back to factual_recall, since asserting
    correct content is the default demand of a Dr. SCI criterion.
    """
    found: set[str] = set()
    if P_RESTRAINT.search(text):
        found.add("restraint")
    if P_PRESENTATION.search(text):
        found.add("presentation")
    if P_QUANTITATIVE.search(text):
        found.add("quantitative")
    if P_RECALL.search(text):
        found.add("factual_recall")
    if P_REASONING.search(text):
        # Precedence, not addition: a criterion demanding an explanation is not satisfied by
        # the bare fact, so leaving factual_recall on would understate what it tests -- and
        # would leave no criterion loading on recall alone.
        found.add("mechanistic_reasoning")
        found.discard("factual_recall")
    if not found:
        found.add("factual_recall")
    return [s for s in SKILLS if s in found]


def q_mapping(marked: list[str]) -> dict[str, int]:
    return {s: int(s in set(marked)) for s in SKILLS}


def objectivity_for(skills: list[str]) -> str:
    """Externally checkable if it turns on a fact or a number; a judgement call otherwise."""
    if "quantitative" in skills or "factual_recall" in skills:
        return "objective"
    return "subjective"


def load_difficulty_index(path: Path) -> dict:
    if not path.exists():
        print(f"note: {path.relative_to(ROOT)} absent -- source_difficulty will be null.\n"
              f"      Build it first to recover Dr. SCI's empirical difficulty.", file=sys.stderr)
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def question_key(prompt_text: str) -> str:
    """Hash of the question with Dr. SCI's instruction wrapper stripped, for index lookup."""
    q = re.sub(r"^Solve the following .*?\$ANSWER is your answer\.\s*", "", prompt_text,
               flags=re.S)
    return hashlib.sha1(q.strip().encode("utf-8")).hexdigest()[:16]


def build(scen_path: Path, rub_path: Path, index: dict) -> tuple[list[dict], list[dict], dict]:
    raw_scen = [json.loads(l) for l in scen_path.open(encoding="utf-8") if l.strip()]
    raw_rub = [json.loads(l) for l in rub_path.open(encoding="utf-8") if l.strip()]
    by_scenario: dict[str, list[dict]] = defaultdict(list)
    for r in raw_rub:
        by_scenario[r["scenario_id"]].append(r)

    scenarios: list[dict] = []
    rubrics: list[dict] = []
    stats = Counter()

    for s in raw_scen:
        sid = s["scenario_id"]
        prompt = flatten_prompt(s.get("prompt"))
        if not prompt:
            stats["dropped_empty_prompt"] += 1
            continue
        mine = sorted(by_scenario.get(sid, []), key=lambda r: r["criterion_id"])
        if not mine:
            stats["dropped_no_criteria"] += 1
            continue

        hit = index.get(question_key(prompt))
        if hit:
            stats["difficulty_recovered"] += 1
        scenarios.append({
            "scenario_id": sid,
            "use_case": USE_CASE,
            "subject": s.get("subject") or "",
            "grade_band": None,                  # Dr. SCI carries no grade level
            "modality": "text",
            "prompt": prompt,
            "conversation_context": [],          # every Dr. SCI item is single-turn
            "reference_solution": (s.get("reference_solution") or "").strip(),
            "criterion_ids": [r["criterion_id"] for r in mine],
            "source_difficulty": (hit or {}).get("difficulty"),
            "source_dataset": (hit or {}).get("from"),
            "source": SOURCE_URL,
            "split": SPLIT,
            "version": VERSION,
        })

        for r in mine:
            category, criterion = split_category(r.get("description") or "")
            if category is None:
                stats["criterion_without_category"] += 1
            skills = assign_skills(f"{r.get('title') or ''} {criterion}")
            weight = r.get("weight")
            pitfall = category == "Pitfall" or (isinstance(weight, int) and weight < 0)
            rubrics.append({
                "criterion_id": r["criterion_id"],
                "scenario_id": sid,
                "criterion": criterion,
                "expected_evidence": [],         # Dr. SCI ships none
                "scoring_type": "binary",
                "score_anchors": None,
                "rubric_title": r.get("title") or "",
                "category": category or "Unlabelled",
                # Inverted: the criterion names something to AVOID, so pass == avoided.
                "polarity": "avoid" if pitfall else "require",
                "source_weight": weight,
                "primary_skill": skills[0],
                "q_mapping": q_mapping(skills),
                "q_rationale": "; ".join(Q_RATIONALE[s] for s in skills)
                               + ("  Scored as: did the response AVOID this mistake?" if pitfall else ""),
                "criticality": CRITICALITY_OF.get(category, "standard"),
                "objectivity": objectivity_for(skills),
                # Dr. SCI prompts ask only for a worked answer; no criterion is spelled out
                # to the model, so every one is an implicit expectation.
                "explicitness": "implicit",
                "source": SOURCE_URL,
                "status": "approved",
                "version": VERSION,
            })
    return scenarios, rubrics, stats


def validate(scenarios: list[dict], rubrics: list[dict]) -> list[str]:
    errs: list[str] = []
    for name, rows, keys in (("scenario", scenarios, SCENARIO_KEYS), ("rubric", rubrics, RUBRIC_KEYS)):
        for r in rows:
            if list(r.keys()) != keys:
                errs.append(f"{name} {list(r.values())[0]}: key set/order mismatch")
                break

    sids = [s["scenario_id"] for s in scenarios]
    cids = [r["criterion_id"] for r in rubrics]
    if len(set(sids)) != len(sids):
        errs.append(f"{len(sids)-len(set(sids))} duplicate scenario_id")
    if len(set(cids)) != len(cids):
        errs.append(f"{len(cids)-len(set(cids))} duplicate criterion_id")

    declared = {c for s in scenarios for c in s["criterion_ids"]}
    actual = set(cids)
    if declared != actual:
        errs.append(f"criterion_ids mismatch: {len(declared-actual)} declared-but-missing, "
                    f"{len(actual-declared)} present-but-undeclared")
    if {r["scenario_id"] for r in rubrics} - set(sids):
        errs.append("rubrics reference unknown scenarios")

    for s in scenarios:
        if not s["prompt"].strip():
            errs.append(f"{s['scenario_id']}: empty prompt")
        if isinstance(s["prompt"], list):
            errs.append(f"{s['scenario_id']}: prompt was not flattened")
        if not s["criterion_ids"]:
            errs.append(f"{s['scenario_id']}: no criteria")

    for r in rubrics:
        if not (r["criterion"] or "").strip():
            errs.append(f"{r['criterion_id']}: empty criterion")
        if CATEGORY_RE.match(r["criterion"]):
            errs.append(f"{r['criterion_id']}: category prefix not stripped")
        q = r["q_mapping"]
        if list(q.keys()) != SKILLS:
            errs.append(f"{r['criterion_id']}: q_mapping keys/order != {SKILLS}")
        if set(q.values()) - {0, 1}:
            errs.append(f"{r['criterion_id']}: q_mapping values must be 0/1")
        if sum(q.values()) < 1:
            errs.append(f"{r['criterion_id']}: q_mapping maps to no skill")
        if r["primary_skill"] not in SKILLS or q.get(r["primary_skill"]) != 1:
            errs.append(f"{r['criterion_id']}: primary_skill not marked in q_mapping")
        if r["polarity"] not in ("require", "avoid"):
            errs.append(f"{r['criterion_id']}: bad polarity {r['polarity']!r}")

    # Every skill needs pure single-loading anchors or its dimension is not separably
    # identified. Two distinct criterion sources is the minimum this bank commits to.
    pure = Counter(r["primary_skill"] for r in rubrics if sum(r["q_mapping"].values()) == 1)
    for s in SKILLS:
        if pure[s] < 50:
            errs.append(f"skill {s!r} has only {pure[s]} pure-loading criteria (<50)")
    return errs


def write(out_dir: Path, name: str, rows: list[dict]) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    p = out_dir / f"{name}.jsonl"
    with p.open("w", encoding="utf-8", newline="\n") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    j = out_dir / f"{name}.json"
    with j.open("w", encoding="utf-8", newline="\n") as fh:
        json.dump(rows, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print(f"wrote {p.relative_to(ROOT)} + .json  ({len(rows)} rows, {p.stat().st_size/1e6:.1f} MB)")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--scenarios", type=Path, default=DEFAULT_SCENARIOS)
    ap.add_argument("--rubrics", type=Path, default=DEFAULT_RUBRICS)
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--index", type=Path, default=DIFFICULTY_INDEX)
    args = ap.parse_args()

    for p in (args.scenarios, args.rubrics):
        if not p.exists():
            raise SystemExit(f"missing input: {p}")

    index = load_difficulty_index(args.index)
    scenarios, rubrics, stats = build(args.scenarios, args.rubrics, index)

    errs = validate(scenarios, rubrics)
    if errs:
        print(f"VALIDATION FAILED ({len(errs)} issues):", file=sys.stderr)
        for e in errs[:20]:
            print(f"  - {e}", file=sys.stderr)
        raise SystemExit(1)
    print(f"validation passed: {len(scenarios):,} scenarios, {len(rubrics):,} criteria")

    write(args.out_dir, "scenarios", scenarios)
    write(args.out_dir, "rubrics", rubrics)

    n = len(rubrics)
    loads = Counter(s for r in rubrics for s in SKILLS if r["q_mapping"][s])
    pure = Counter(r["primary_skill"] for r in rubrics if sum(r["q_mapping"].values()) == 1)
    wpos = Counter()
    tot = 0
    for r in rubrics:
        w = r["source_weight"]
        if isinstance(w, int) and w > 0:
            tot += w
            for s in SKILLS:
                if r["q_mapping"][s]:
                    wpos[s] += w
    print("\nq-matrix loads / share / pure anchors:")
    for s in SKILLS:
        share = 100 * wpos[s] / tot if tot else 0
        print(f"  {s:<24}{loads[s]:>7} ({100*loads[s]/n:>5.1f}%)  weight {share:>5.1f}%  pure {pure[s]:>6}")
    print("\nloadings per criterion:",
          dict(sorted(Counter(sum(r['q_mapping'].values()) for r in rubrics).items())))
    print("criticality:", dict(Counter(r["criticality"] for r in rubrics).most_common()))
    print("category   :", dict(Counter(r["category"] for r in rubrics).most_common()))
    print("polarity   :", dict(Counter(r["polarity"] for r in rubrics).most_common()))
    print("subjects   :", dict(Counter(s["subject"] for s in scenarios).most_common()))
    got = sum(1 for s in scenarios if s["source_difficulty"] is not None)
    print(f"\nsource_difficulty recovered: {got:,}/{len(scenarios):,}")
    if got:
        print("  distribution (higher = EASIER; 1.0 absent, 8/8-solved were deleted):",
              dict(sorted(Counter(s["source_difficulty"] for s in scenarios
                                  if s["source_difficulty"] is not None).items())))
    if stats:
        print("\nnotes:", dict(stats))
    print("\ndifficulty/discrimination: absent by design -- to be calibrated from real judge "
          "responses, not synthesised.")


if __name__ == "__main__":
    main()
